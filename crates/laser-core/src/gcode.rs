        // 整圆
        let e = motion_extents("G90\nG0 X10 Y0\nG2 X10 Y0 I-10 J0")
            .unwrap()
            .unwrap();
        assert!((e.width() - 20.0).abs() < 1e-9 && (e.height() - 20.0).abs() < 1e-9);
