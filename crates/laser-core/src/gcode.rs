        let e = motion_extents("G1 X5\nX40 ; X999\n(Y999) Y7")
            .unwrap()
            .unwrap();
        assert_eq!((e.max_x, e.max_y), (40.0, 7.0));
        assert_eq!(motion_extents("G21\nM5\n").unwrap(), None);
        assert!(motion_extents("G53 G0 X0 Y0").is_err());
