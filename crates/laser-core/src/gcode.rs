/// `close_paths=true`：把每条路径视为闭合轮廓（字形），补画末点→首点；
/// `close_paths=false`：按原样绘制开放折线（解析自 G-code 的轨迹已包含所有真实线段）。
pub fn preview_outline_rgba_with_options(
    paths: &Paths,
    width: u32,
    height: u32,
    width_mm: f64,
    height_mm: f64,
    close_paths: bool,
) -> Result<image::RgbaImage, &'static str> {
    if width == 0
        || height == 0
        || !width_mm.is_finite()
        || !height_mm.is_finite()
        || width_mm <= 0.0
        || height_mm <= 0.0
    {
        return Err("invalid preview dimensions");
    }

    let mut image = image::RgbaImage::from_pixel(width, height, image::Rgba([0, 0, 0, 0]));

    let mut min_x = f64::INFINITY;
    let mut min_y = f64::INFINITY;
    let mut max_x = f64::NEG_INFINITY;
    let mut max_y = f64::NEG_INFINITY;

    for (x, y) in paths.iter().flatten() {
        if x.is_finite() && y.is_finite() {
            min_x = min_x.min(*x);
            min_y = min_y.min(*y);
            max_x = max_x.max(*x);
            max_y = max_y.max(*y);
        }
    }

    if !min_x.is_finite() {
        min_x = 0.0;
        max_x = width_mm;
        min_y = 0.0;
        max_y = height_mm;
    }

    let content_w = (max_x - min_x).max(0.1);
    let content_h = (max_y - min_y).max(0.1);

    // 预留 15% 边距，居中且严格锁定几何长宽比，杜绝字符变形与切边
    let margin_x = width as f64 * 0.15;
    let margin_y = height as f64 * 0.15;
    let draw_w = (width as f64) - margin_x * 2.0;
    let draw_h = (height as f64) - margin_y * 2.0;

    let scale = (draw_w / content_w).min(draw_h / content_h);

    let offset_x = margin_x + (draw_w - content_w * scale) * 0.5 - min_x * scale;
    let offset_y = margin_y + (draw_h - content_h * scale) * 0.5 - min_y * scale;

    let w_i32 = width as i32;
    let h_i32 = height as i32;

    for path in paths {
        if path.len() < 2 {
            continue;
        }
        let mut pairs: Vec<(
            laser_contracts::geometry::Point,
            laser_contracts::geometry::Point,
        )> = path.windows(2).map(|w| (w[0], w[1])).collect();
        if close_paths && path.len() > 2 {
            let first = path[0];
            let last = *path.last().unwrap();
            if (first.0 - last.0).hypot(first.1 - last.1) > 0.01 {
                pairs.push((last, first));
            }
        }
        for (p0, p1) in pairs {
            let (x0, y0) = p0;
            let (x1, y1) = p1;
            if !x0.is_finite() || !y0.is_finite() || !x1.is_finite() || !y1.is_finite() {
                return Err("path contains non-finite coordinates");
            }
            let px0 = x0 * scale + offset_x;
            let py0 = y0 * scale + offset_y;
            let px1 = x1 * scale + offset_x;
            let py1 = y1 * scale + offset_y;

            // 自动缩放通常已把轨迹装进画布；仍按画布（含 2px 光晕）裁剪，保证单段步数有界
            let Some((t0, t1)) = clip_segment(
                (px0, py0),
                (px1, py1),
                (-3.0, -3.0),
                (f64::from(width) + 3.0, f64::from(height) + 3.0),
            ) else {
                continue;
            };
            let (sx0, sy0) = (px0 + (px1 - px0) * t0, py0 + (py1 - py0) * t0);
            let (sx1, sy1) = (px0 + (px1 - px0) * t1, py0 + (py1 - py0) * t1);
            let dist_px = (sx1 - sx0).hypot(sy1 - sy0);
            let steps = (dist_px * 2.0).ceil() as u32;
            let steps = steps.max(1);

            for step in 0..=steps {
                let t = f64::from(step) / f64::from(steps);
                let cx = (sx0 + (sx1 - sx0) * t).round() as i32;
                let cy = (sy0 + (sy1 - sy0) * t).round() as i32;

                // 绘制高对比度多层激光等离子发光线条 (3px 线宽 + 高光白芯)
                for dy in -2..=2 {
                    for dx in -2..=2 {
                        let nx = cx + dx;
                        let ny = cy + dy;
                        if nx >= 0 && ny >= 0 && nx < w_i32 && ny < h_i32 {
                            let d2 = dx * dx + dy * dy;
                            let target_pixel = image.get_pixel_mut(nx as u32, ny as u32);
                            if d2 == 0 {
                                // 白炽线芯
                                *target_pixel = image::Rgba([240, 252, 255, 255]);
                            } else if d2 <= 2 {
                                // 激光青高能主光束
                                if target_pixel.0[3] < 220 {
                                    *target_pixel = image::Rgba([0, 229, 255, 220]);
                                }
                            } else if d2 <= 4 {
                                // 柔和外围等离子光晕
                                if target_pixel.0[3] < 90 {
                                    *target_pixel = image::Rgba([0, 229, 255, 90]);
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    Ok(image)
}

fn words(line: &str) -> Vec<(char, f64)> {
    let line = line.split(';').next().unwrap_or("");
    let mut out = Vec::new();
    let bytes = line.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'(' {
            while i < bytes.len() && bytes[i] != b')' {
                i += 1;
            }
            i += 1;
            continue;
        }
        if bytes[i].is_ascii_alphabetic() {
            let letter = bytes[i].to_ascii_uppercase() as char;
            let start = i;
            i += 1;
            while i < bytes.len()
                && (bytes[i].is_ascii_digit()
                    || matches!(bytes[i], b'+' | b'-' | b'.' | b'e' | b'E'))
            {
                i += 1;
            }
            if i > start + 1
                && let Ok(value) = line[start + 1..i].parse()
            {
                out.push((letter, value));
            }
        } else {
            i += 1;
        }
    }
    out
}

pub fn parse_moves(text: &str) -> Vec<Move> {
    let mut motion = 0;
    let mut feed = None;
    let mut power = None;
    let mut out = Vec::new();
    for line in text.lines() {
        let ws = words(line);
        for &(letter, value) in &ws {
            if letter == 'G'
                && matches!(value as i32, 0 | 1)
                && (value - value.round()).abs() < 1e-9
            {
                motion = value as i32;
            } else if letter == 'F' {
                feed = Some(value);
            } else if letter == 'S' {
                power = Some(value);
            }
        }
        if ws
            .iter()
            .any(|&(l, v)| l == 'G' && (v - v.round()).abs() < 1e-9 && matches!(v as i32, 0 | 1))
            && ws.iter().any(|&(l, _)| l == 'X' || l == 'Y')
        {
            out.push(Move {
                x: ws.iter().rev().find(|(l, _)| *l == 'X').map(|(_, v)| *v),
                y: ws.iter().rev().find(|(l, _)| *l == 'Y').map(|(_, v)| *v),
                feed_rate: feed,
                power,
                rapid: motion == 0,
            });
        }
    }
    out
}

/// 刀路实际走到的范围（mm，相对任务开始时激光头所在位置；起点本身计入）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MotionExtents {
    pub min_x: f64,
    pub max_x: f64,
    pub min_y: f64,
    pub max_y: f64,
}

impl MotionExtents {
    pub fn width(&self) -> f64 {
        self.max_x - self.min_x
    }

    pub fn height(&self) -> f64 {
        self.max_y - self.min_y
    }

    fn include(&mut self, x: f64, y: f64) {
        self.min_x = self.min_x.min(x);
        self.max_x = self.max_x.max(x);
        self.min_y = self.min_y.min(y);
        self.max_y = self.max_y.max(y);
    }
}

/// 计算激光头在整份 G-code 中走过的 X/Y 范围，用于发送前与机器行程比对（2026-11-06）。
/// - 跟踪 G90/G91、G20/G21；`G92` 只改坐标原点不移动（生成的任务以 `G92 X0 Y0` 把当前位置设为原点）；
/// - 快速移动也计入（激光头同样会走到）；G2/G3 圆弧计入经过的最左 / 右 / 上 / 下点，`R` 写法按以弦中点为心、
///   半径 |R| 的圆保守计入；
/// - `G53` / `G28` / `G30` 等以机床坐标或回参考点移动的行无法从文件本身得知终点，返回 `Err` 让调用方拒绝。
///
/// 没有任何 X/Y 移动时返回 `Ok(None)`。
pub fn motion_extents(text: &str) -> Result<Option<MotionExtents>, String> {
    let (mut px, mut py) = (0.0_f64, 0.0_f64); // 物理位置（相对开始点）
    let (mut ox, mut oy) = (0.0_f64, 0.0_f64); // 工件坐标原点相对开始点的偏移
    let mut absolute = true;
    let mut unit = 1.0;
    let mut motion = 0;
    let mut extents = MotionExtents {
        min_x: 0.0,
        max_x: 0.0,
        min_y: 0.0,
        max_y: 0.0,
    };
    let mut moved = false;
    for (index, line) in text.lines().enumerate() {
        let ws = words(line);
        if ws.is_empty() {
            continue;
        }
        let g_codes: Vec<f64> = ws
            .iter()
            .filter(|(l, _)| *l == 'G')
            .map(|(_, v)| *v)
            .collect();
        let has = |code: f64| g_codes.iter().any(|v| (v - code).abs() < 1e-9);
        let word = |letter: char| ws.iter().rev().find(|(l, _)| *l == letter).map(|(_, v)| *v);
        if has(20.0) {
            unit = 25.4;
        }
        if has(21.0) {
            unit = 1.0;
        }
        if has(90.0) {
            absolute = true;
        }
        if has(91.0) {
            absolute = false;
        }
        let (x, y) = (word('X'), word('Y'));
        if has(92.0) {
            // G92 Xa：当前位置在新坐标系里记为 a
            if let Some(v) = x {
                ox = px - v * unit;
            }
            if let Some(v) = y {
                oy = py - v * unit;
            }
            if x.is_none() && y.is_none() {
                ox = px;
                oy = py;
            }
            continue;
        }
        if [53.0, 28.0, 30.0, 10.0].iter().any(|code| has(*code))
            && (x.is_some() || y.is_some() || has(28.0) || has(30.0))
        {
            return Err(format!(
                "第 {} 行使用机床坐标、回参考点或改坐标系指令（{}），无法从文件计算加工范围",
                index + 1,
                line.trim()
            ));
        }
        for code in &g_codes {
            if [0.0, 1.0, 2.0, 3.0].iter().any(|m| (code - m).abs() < 1e-9) {
                motion = *code as i32;
            }
        }
        if x.is_none() && y.is_none() {
            continue;
        }
        let (sx, sy) = (px, py);
        let target = |current: f64, origin: f64, value: Option<f64>| match value {
            None => current,
            Some(v) if absolute => origin + v * unit,
            Some(v) => current + v * unit,
        };
        let (tx, ty) = (target(px, ox, x), target(py, oy, y));
        if !(tx.is_finite() && ty.is_finite()) {
            return Err(format!("第 {} 行坐标不是有限数", index + 1));
        }
        moved = true;
        extents.include(tx, ty);
        if motion == 2 || motion == 3 {
            if let Some(r) = word('R') {
                let (cx, cy, radius) = ((sx + tx) / 2.0, (sy + ty) / 2.0, r.abs() * unit);
                extents.include(cx - radius, cy - radius);
                extents.include(cx + radius, cy + radius);
            } else {
                let (cx, cy) = (
                    sx + word('I').unwrap_or(0.0) * unit,
                    sy + word('J').unwrap_or(0.0) * unit,
                );
                let radius = (sx - cx).hypot(sy - cy);
                let start = (sy - cy).atan2(sx - cx);
                let end = (ty - cy).atan2(tx - cx);
                let full = (sx - tx).abs() < 1e-9 && (sy - ty).abs() < 1e-9;
                let tau = std::f64::consts::TAU;
                // 逆时针（G3）从 start 扫到 end；顺时针（G2）反向
                let (from, sweep) = if motion == 3 {
                    (
                        start,
                        if full {
                            tau
                        } else {
                            (end - start).rem_euclid(tau)
                        },
                    )
                } else {
                    (
                        end,
                        if full {
                            tau
                        } else {
                            (start - end).rem_euclid(tau)
                        },
                    )
                };
                for quadrant in 0..4 {
                    let angle = f64::from(quadrant) * std::f64::consts::FRAC_PI_2;
                    if (angle - from).rem_euclid(tau) <= sweep + 1e-12 {
                        extents.include(cx + radius * angle.cos(), cy + radius * angle.sin());
                    }
                }
            }
        }
        px = tx;
        py = ty;
    }
    Ok(moved.then_some(extents))
}

pub fn write_move(m: &Move) -> String {
    let mut line = if m.rapid { "G0" } else { "G1" }.to_owned();
    if let Some(x) = m.x {
        write!(line, " X{x:.3}").unwrap();
    }
    if let Some(y) = m.y {
        write!(line, " Y{y:.3}").unwrap();
    }
    if let Some(feed) = m.feed_rate {
        write!(line, " F{feed:.0}").unwrap();
    }
    if let Some(power) = m.power {
        write!(line, " S{power:.0}").unwrap();
    }
    line
}

