#[derive(Debug, Clone, PartialEq)]
pub struct WriterOptions {
    pub width_mm: f64,
    pub height_mm: f64,
    pub power: i32,
    pub feed_rate: i32,
    pub auto_close: bool,
    pub laser_mode: &'static str,
    pub power_scale: Option<i32>,
}

pub fn write_outline(paths: &Paths, options: &WriterOptions) -> Result<String, &'static str> {
    let scale = options.power_scale.unwrap_or(1000);
    if !options.width_mm.is_finite()
        || !options.height_mm.is_finite()
        || options.width_mm <= 0.0
        || options.height_mm <= 0.0
        || options.power < 0
        || options.power > scale
        || options.feed_rate < 1
    {
        return Err("invalid writer options");
    }
    let mut lines = vec![
        "; Generated by laser-core".to_owned(),
        format!("; GRBL laser mode expected: $30={scale}, $32=1"),
        "G21".into(),
        "G90".into(),
        "G94".into(),
        "G17".into(),
        "G92 X0 Y0 Z0".into(),
        format!("{} S0", options.laser_mode),
        "G0 F3000".into(),
    ];
    let mut current_feed: Option<i32> = None;
    for path in paths {
        if path.is_empty() {
            continue;
        }
        let point = |(x, y): (f64, f64)| -> Result<(f64, f64), &'static str> {
            if !x.is_finite() || !y.is_finite() {
                return Err("path contains non-finite coordinates");
            }
            Ok((x, options.height_mm - y))
        };
        let start = point(path[0])?;
        lines.push(format!("G0 X{:.3} Y{:.3}", start.0, start.1));
        for &vertex in path.iter().skip(1) {
            let (x, y) = point(vertex)?;
            let f_part = if current_feed != Some(options.feed_rate) {
                current_feed = Some(options.feed_rate);
                format!(" F{}", options.feed_rate)
            } else {
                String::new()
            };
            lines.push(format!(
                "G1 X{x:.3} Y{y:.3} S{}{f_part}",
                options.power
            ));
        }
        if options.auto_close && path.len() > 2 && path.last() != path.first() {
            let f_part = if current_feed != Some(options.feed_rate) {
                current_feed = Some(options.feed_rate);
                format!(" F{}", options.feed_rate)
            } else {
                String::new()
            };
            lines.push(format!(
                "G1 X{:.3} Y{:.3} S{}{f_part}",
                start.0, start.1, options.power
            ));
        }
        lines.push("S0".into());
    }
    lines.extend(["M5".into(), "M2".into()]);
    Ok(lines.join("\n") + "\n")
}

/// 生成红光轮廓预览 (Framing) G-code：
/// 沿指定外接矩形 (min_x, min_y, max_x, max_y) 绕行一圈，用于在材料上定位工件摆放位置。
/// power 通常设为 0（仅轴运动）或微弱光斑（如 1，即 0.1% 功率）。
pub fn generate_framing_gcode(
    min_x: f64,
    min_y: f64,
    max_x: f64,
    max_y: f64,
    feed_rate: i32,
    power: i32,
) -> Result<String, &'static str> {
    if !min_x.is_finite() || !min_y.is_finite() || !max_x.is_finite() || !max_y.is_finite() {
        return Err("framing coordinates must be finite");
    }
    if min_x > max_x || min_y > max_y || feed_rate < 1 || power < 0 {
        return Err("invalid framing parameters");
    }
    let mut lines = vec![
        "; Generated by laser-core (Framing Preview)".to_owned(),
        "G21".into(),
        "G90".into(),
        "G94".into(),
        "G17".into(),
        "M5 S0".into(),
        format!("G0 X{min_x:.3} Y{min_y:.3} F3000"),
    ];
    if power > 0 {
        lines.push(format!("M4 S{power}"));
    }
    lines.push(format!("G1 X{max_x:.3} Y{min_y:.3} F{feed_rate}"));
    lines.push(format!("G1 X{max_x:.3} Y{max_y:.3}"));
    lines.push(format!("G1 X{min_x:.3} Y{max_y:.3}"));
    lines.push(format!("G1 X{min_x:.3} Y{min_y:.3}"));
    lines.push("M5 S0".into());
    lines.push("G0 X0 Y0 F3000".into());
    lines.push("M2".into());
    Ok(lines.join("\n") + "\n")
}

/// 基于路径几何计算外接矩形并生成红光走边框 G-code。
pub fn generate_paths_framing_gcode(
    paths: &Paths,
    height_mm: f64,
    feed_rate: i32,
    power: i32,
) -> Result<String, &'static str> {
    let mut min_x = f64::INFINITY;
    let mut min_y = f64::INFINITY;
    let mut max_x = f64::NEG_INFINITY;
    let mut max_y = f64::NEG_INFINITY;
    for path in paths {
        for &(x, y) in path {
            let actual_y = height_mm - y;
            min_x = min_x.min(x);
            max_x = max_x.max(x);
            min_y = min_y.min(actual_y);
            max_y = max_y.max(actual_y);
        }
    }
    if !min_x.is_finite() || !min_y.is_finite() {
        return Err("paths are empty");
    }
    generate_framing_gcode(min_x, min_y, max_x, max_y, feed_rate, power)
}

#[derive(Debug, Clone, PartialEq)]
pub struct RasterWriterOptions {
    pub pixel_size_mm: f64,
    pub overscan_mm: f64,
    pub work_area_width_mm: f64,
    pub work_area_height_mm: f64,
    pub power: i32,
    pub feed_rate: i32,
    pub laser_mode: &'static str,
    pub snake_scan: bool,
    pub material: Option<String>,
    pub safety_note: Option<String>,
    pub power_scale: Option<i32>,
}

pub fn write_raster(
    plan: &RasterPlan,
    grid_width: usize,
    grid_height: usize,
    options: &RasterWriterOptions,
) -> Result<String, &'static str> {
    let scale = options.power_scale.unwrap_or(1000);
    if grid_width == 0
        || grid_height == 0
        || !options.pixel_size_mm.is_finite()
        || options.pixel_size_mm <= 0.0
        || !options.overscan_mm.is_finite()
        || options.overscan_mm < 0.0
        || !options.work_area_width_mm.is_finite()
        || options.work_area_width_mm <= 0.0
        || !options.work_area_height_mm.is_finite()
        || options.work_area_height_mm <= 0.0
        || options.power < 0
        || options.power > scale
        || options.feed_rate < 1
    {
        return Err("invalid raster writer options");
    }

    let height_mm = grid_height as f64 * options.pixel_size_mm;
    let material_str = options.material.as_deref().unwrap_or("generic");
    let note_str = options.safety_note.as_deref().unwrap_or("auto");

    let mut lines = vec![
        "; Generated by ai-laser-gcode-nc".to_string(),
        format!("; GRBL laser mode expected: $30={scale}, $32=1"),
        format!("; Material: {}; note: {}", material_str, note_str),
        "; Raster mode: black/white dithered scan".to_string(),
        "G21".to_string(),
        "G90".to_string(),
        "G94".to_string(),
        "G17".to_string(),
        "G92 X0 Y0 Z0".to_string(),
        format!("{} S0", options.laser_mode),
        "G0 F3000".to_string(),
    ];

    let segments = if plan.selected_axis == "vertical" {
        &plan.vertical
    } else {
        &plan.horizontal
    };

    #[derive(Clone, Copy)]
    struct MachineSegment {
        start_x_mm: f64,
        end_x_mm: f64,
        y_mm: f64,
        end_y_mm: f64,
    }

    let machine_segs: Vec<MachineSegment> = if plan.selected_axis == "vertical" {
        let mut segs: Vec<MachineSegment> = segments
            .iter()
            .map(|seg| {
                let start_x_mm = seg.line as f64 * options.pixel_size_mm;
                let orig_y = seg.start as f64 * options.pixel_size_mm;
                let orig_end_y = seg.end as f64 * options.pixel_size_mm;
                let y_mm = (height_mm - orig_end_y).max(0.0);
                let end_y_mm = (height_mm - orig_y).max(0.0);
                MachineSegment {
                    start_x_mm,
                    end_x_mm: start_x_mm,
                    y_mm,
                    end_y_mm,
                }
            })
            .collect();
        segs.sort_by(|a, b| {
            a.start_x_mm
                .partial_cmp(&b.start_x_mm)
                .unwrap()
                .then_with(|| a.y_mm.partial_cmp(&b.y_mm).unwrap())
                .then_with(|| a.end_y_mm.partial_cmp(&b.end_y_mm).unwrap())
        });
        segs
    } else {
        let mut segs: Vec<MachineSegment> = segments
            .iter()
            .map(|seg| {
                let orig_y = seg.line as f64 * options.pixel_size_mm;
                let y_mm = (height_mm - options.pixel_size_mm - orig_y).max(0.0);
                let start_x_mm = seg.start as f64 * options.pixel_size_mm;
                let end_x_mm = seg.end as f64 * options.pixel_size_mm;
                MachineSegment {
                    start_x_mm,
                    end_x_mm,
                    y_mm,
                    end_y_mm: y_mm,
                }
            })
            .collect();
        segs.sort_by(|a, b| {
            a.y_mm
                .partial_cmp(&b.y_mm)
                .unwrap()
                .then_with(|| a.start_x_mm.partial_cmp(&b.start_x_mm).unwrap())
                .then_with(|| a.end_x_mm.partial_cmp(&b.end_x_mm).unwrap())
        });
        segs
    };

    let mut current_feed: Option<i32> = None;

    if plan.output_strategy == "scanline" {
        let mut groups: Vec<Vec<MachineSegment>> = Vec::new();
        for seg in machine_segs {
            let key = if plan.selected_axis == "vertical" {
                seg.start_x_mm
            } else {
                seg.y_mm
            };
            if let Some(last_group) = groups.last_mut() {
                let last_key = if plan.selected_axis == "vertical" {
                    last_group[0].start_x_mm
                } else {
                    last_group[0].y_mm
                };
                if (key - last_key).abs() < 1e-6 {
                    last_group.push(seg);
                    continue;
                }
            }
            groups.push(vec![seg]);
        }

        for (line_index, line_segs) in groups.into_iter().enumerate() {
            if line_segs.is_empty() {
                continue;
            }
            let reverse = options.snake_scan && line_index % 2 == 1;

            if plan.selected_axis == "vertical" {
                let x_coord = line_segs[0].start_x_mm;
                let mut shifted_runs: Vec<(f64, f64)> = line_segs
                    .iter()
                    .map(|seg| (seg.y_mm + options.overscan_mm, seg.end_y_mm + options.overscan_mm))
                    .collect();
                shifted_runs.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap());

                let min_start = shifted_runs.iter().map(|(s, _)| *s).fold(f64::INFINITY, f64::min);
                let max_end = shifted_runs.iter().map(|(_, e)| *e).fold(f64::NEG_INFINITY, f64::max);
                let scan_start = (min_start - options.overscan_mm).max(0.0);
                let scan_end = (max_end + options.overscan_mm).min(options.work_area_height_mm);

                if reverse {
                    lines.push(format!("G0 X{x_coord:.3} Y{scan_end:.3}"));
                    for (start_y, end_y) in shifted_runs.into_iter().rev() {
                        let f_part = if current_feed != Some(options.feed_rate) {
                            current_feed = Some(options.feed_rate);
                            format!(" F{}", options.feed_rate)
                        } else {
                            String::new()
                        };
                        lines.push(format!("G1 Y{end_y:.3} S0{f_part}"));
                        lines.push(format!("G1 Y{start_y:.3} S{}", options.power));
                    }
                    lines.push(format!("G1 Y{scan_start:.3} S0"));
                } else {
                    lines.push(format!("G0 X{x_coord:.3} Y{scan_start:.3}"));
                    for (start_y, end_y) in shifted_runs {
                        let f_part = if current_feed != Some(options.feed_rate) {
                            current_feed = Some(options.feed_rate);
                            format!(" F{}", options.feed_rate)
                        } else {
                            String::new()
                        };
                        lines.push(format!("G1 Y{start_y:.3} S0{f_part}"));
                        lines.push(format!("G1 Y{end_y:.3} S{}", options.power));
                    }
                    lines.push(format!("G1 Y{scan_end:.3} S0"));
                }
            } else {
                let y_coord = line_segs[0].y_mm;
                let mut shifted_runs: Vec<(f64, f64)> = line_segs
                    .iter()
                    .map(|seg| (seg.start_x_mm + options.overscan_mm, seg.end_x_mm + options.overscan_mm))
                    .collect();
                shifted_runs.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap());

                let min_start = shifted_runs.iter().map(|(s, _)| *s).fold(f64::INFINITY, f64::min);
                let max_end = shifted_runs.iter().map(|(_, e)| *e).fold(f64::NEG_INFINITY, f64::max);
                let scan_start = (min_start - options.overscan_mm).max(0.0);
                let scan_end = (max_end + options.overscan_mm).min(options.work_area_width_mm);

                if reverse {
                    lines.push(format!("G0 X{scan_end:.3} Y{y_coord:.3}"));
                    for (start_x, end_x) in shifted_runs.into_iter().rev() {
                        let f_part = if current_feed != Some(options.feed_rate) {
                            current_feed = Some(options.feed_rate);
                            format!(" F{}", options.feed_rate)
                        } else {
                            String::new()
                        };
                        lines.push(format!("G1 X{end_x:.3} S0{f_part}"));
                        lines.push(format!("G1 X{start_x:.3} S{}", options.power));
                    }
                    lines.push(format!("G1 X{scan_start:.3} S0"));
                } else {
                    lines.push(format!("G0 X{scan_start:.3} Y{y_coord:.3}"));
                    for (start_x, end_x) in shifted_runs {
                        let f_part = if current_feed != Some(options.feed_rate) {
                            current_feed = Some(options.feed_rate);
                            format!(" F{}", options.feed_rate)
                        } else {
                            String::new()
                        };
                        lines.push(format!("G1 X{start_x:.3} S0{f_part}"));
                        lines.push(format!("G1 X{end_x:.3} S{}", options.power));
                    }
                    lines.push(format!("G1 X{scan_end:.3} S0"));
                }
            }
        }
    } else {
        for seg in segments {
            if plan.selected_axis == "vertical" {
                let x_coord = seg.line as f64 * options.pixel_size_mm;
                let orig_y = seg.start as f64 * options.pixel_size_mm;
                let orig_end_y = seg.end as f64 * options.pixel_size_mm;
                let machine_y = (height_mm - orig_end_y).max(0.0);
                let machine_end_y = (height_mm - orig_y).max(0.0);

                let start_y = machine_y + options.overscan_mm;
                let end_y = machine_end_y + options.overscan_mm;
                let overscan_start = (start_y - options.overscan_mm).max(0.0);
                let overscan_end = (end_y + options.overscan_mm).min(options.work_area_height_mm);

                lines.push(format!("G0 X{x_coord:.3} Y{overscan_start:.3}"));
                let f_part = if current_feed != Some(options.feed_rate) {
                    current_feed = Some(options.feed_rate);
                    format!(" F{}", options.feed_rate)
                } else {
                    String::new()
                };
                lines.push(format!("G1 Y{start_y:.3} S0{f_part}"));
                lines.push(format!("G1 Y{end_y:.3} S{}", options.power));
                lines.push(format!("G1 Y{overscan_end:.3} S0"));
            } else {
                let orig_y = seg.line as f64 * options.pixel_size_mm;
                let y_coord = (height_mm - options.pixel_size_mm - orig_y).max(0.0);
                let start_x = seg.start as f64 * options.pixel_size_mm + options.overscan_mm;
                let end_x = seg.end as f64 * options.pixel_size_mm + options.overscan_mm;
                let overscan_start = (start_x - options.overscan_mm).max(0.0);
                let overscan_end = (end_x + options.overscan_mm).min(options.work_area_width_mm);

                lines.push(format!("G0 X{overscan_start:.3} Y{y_coord:.3}"));
                let f_part = if current_feed != Some(options.feed_rate) {
                    current_feed = Some(options.feed_rate);
                    format!(" F{}", options.feed_rate)
                } else {
                    String::new()
                };
                lines.push(format!("G1 X{start_x:.3} S0{f_part}"));
                lines.push(format!("G1 X{end_x:.3} S{}", options.power));
                lines.push(format!("G1 X{overscan_end:.3} S0"));
            }
        }
    }

    lines.push("M5".to_string());
    lines.push("M2".to_string());
    Ok(lines.join("\n") + "\n")
}

pub fn preview_outline(
    paths: &Paths,
    width: u32,
    height: u32,
    width_mm: f64,
    height_mm: f64,
) -> Result<image::GrayImage, &'static str> {
    if width == 0
        || height == 0
        || !width_mm.is_finite()
        || !height_mm.is_finite()
        || width_mm <= 0.0
        || height_mm <= 0.0
    {
        return Err("invalid preview dimensions");
    }
    let mut image = image::GrayImage::from_pixel(width, height, image::Luma([255]));
    let sx = f64::from(width.saturating_sub(1)) / width_mm;
    let sy = f64::from(height.saturating_sub(1)) / height_mm;
    for path in paths {
        if path.len() < 2 {
            continue;
        }
        let mut pairs: Vec<(laser_contracts::geometry::Point, laser_contracts::geometry::Point)> =
            path.windows(2).map(|w| (w[0], w[1])).collect();
        if path.len() > 2 {
            let first = path[0];
            let last = *path.last().unwrap();
            if (first.0 - last.0).hypot(first.1 - last.1) > 0.01 {
                pairs.push((last, first));
            }
        }
        for (p0, p1) in pairs {
            let (x0, y0) = p0;
            let (x1, y1) = p1;
            if !x0.is_finite() || !y0.is_finite() || !x1.is_finite() || !y1.is_finite() {
                return Err("path contains non-finite coordinates");
            }
            let mut steps = ((x1 - x0).hypot(y1 - y0) * sx.max(sy)).ceil() as u32;
            steps = steps.max(1);
            for step in 0..=steps {
                let t = f64::from(step) / f64::from(steps);
                let px = (x0 + (x1 - x0) * t) * sx;
                let py = (y0 + (y1 - y0) * t) * sy;
                if px >= 0.0 && py >= 0.0 && px < f64::from(width) && py < f64::from(height) {
                    image.put_pixel(px as u32, py as u32, image::Luma([0]));
                }
            }
        }
    }
    Ok(image)
}

pub fn preview_outline_rgba(
    paths: &Paths,
    width: u32,
    height: u32,
    width_mm: f64,
    height_mm: f64,
) -> Result<image::RgbaImage, &'static str> {
    preview_outline_rgba_with_options(paths, width, height, width_mm, height_mm, true)
}

/// `close_paths=true`：把每条路径视为闭合轮廓（字形），补画末点→首点；
/// `close_paths=false`：按原样绘制开放折线（解析自 G-code 的轨迹已包含所有真实线段）。
pub fn preview_outline_rgba_with_options(
    paths: &Paths,
    width: u32,
    height: u32,
    width_mm: f64,
    height_mm: f64,
    close_paths: bool,
) -> Result<image::RgbaImage, &'static str> {
    if width == 0
        || height == 0
        || !width_mm.is_finite()
        || !height_mm.is_finite()
        || width_mm <= 0.0
        || height_mm <= 0.0
    {
        return Err("invalid preview dimensions");
    }

    let mut image = image::RgbaImage::from_pixel(width, height, image::Rgba([0, 0, 0, 0]));

    let mut min_x = f64::INFINITY;
    let mut min_y = f64::INFINITY;
    let mut max_x = f64::NEG_INFINITY;
    let mut max_y = f64::NEG_INFINITY;

    for (x, y) in paths.iter().flatten() {
        if x.is_finite() && y.is_finite() {
            min_x = min_x.min(*x);
            min_y = min_y.min(*y);
            max_x = max_x.max(*x);
            max_y = max_y.max(*y);
        }
    }

    if !min_x.is_finite() {
        min_x = 0.0;
        max_x = width_mm;
        min_y = 0.0;
        max_y = height_mm;
    }

    let content_w = (max_x - min_x).max(0.1);
    let content_h = (max_y - min_y).max(0.1);

    // 预留 15% 边距，居中且严格锁定几何长宽比，杜绝字符变形与切边
    let margin_x = width as f64 * 0.15;
    let margin_y = height as f64 * 0.15;
    let draw_w = (width as f64) - margin_x * 2.0;
    let draw_h = (height as f64) - margin_y * 2.0;

    let scale = (draw_w / content_w).min(draw_h / content_h);

    let offset_x = margin_x + (draw_w - content_w * scale) * 0.5 - min_x * scale;
    let offset_y = margin_y + (draw_h - content_h * scale) * 0.5 - min_y * scale;

    let w_i32 = width as i32;
    let h_i32 = height as i32;

    for path in paths {
        if path.len() < 2 {
            continue;
        }
        let mut pairs: Vec<(laser_contracts::geometry::Point, laser_contracts::geometry::Point)> =
            path.windows(2).map(|w| (w[0], w[1])).collect();
        if close_paths && path.len() > 2 {
            let first = path[0];
            let last = *path.last().unwrap();
            if (first.0 - last.0).hypot(first.1 - last.1) > 0.01 {
                pairs.push((last, first));
            }
        }
        for (p0, p1) in pairs {
            let (x0, y0) = p0;
            let (x1, y1) = p1;
            if !x0.is_finite() || !y0.is_finite() || !x1.is_finite() || !y1.is_finite() {
                return Err("path contains non-finite coordinates");
            }
            let px0 = x0 * scale + offset_x;
            let py0 = y0 * scale + offset_y;
            let px1 = x1 * scale + offset_x;
            let py1 = y1 * scale + offset_y;

            let dist_px = (px1 - px0).hypot(py1 - py0);
            let steps = (dist_px * 2.0).ceil() as u32;
            let steps = steps.max(1);

            for step in 0..=steps {
                let t = f64::from(step) / f64::from(steps);
                let cx = (px0 + (px1 - px0) * t).round() as i32;
                let cy = (py0 + (py1 - py0) * t).round() as i32;

                // 绘制高对比度多层激光等离子发光线条 (3px 线宽 + 高光白芯)
                for dy in -2..=2 {
                    for dx in -2..=2 {
                        let nx = cx + dx;
                        let ny = cy + dy;
                        if nx >= 0 && ny >= 0 && nx < w_i32 && ny < h_i32 {
                            let d2 = dx * dx + dy * dy;
                            let target_pixel = image.get_pixel_mut(nx as u32, ny as u32);
                            if d2 == 0 {
                                // 白炽线芯
                                *target_pixel = image::Rgba([240, 252, 255, 255]);
                            } else if d2 <= 2 {
                                // 激光青高能主光束
                                if target_pixel.0[3] < 220 {
                                    *target_pixel = image::Rgba([0, 229, 255, 220]);
                                }
                            } else if d2 <= 4 {
                                // 柔和外围等离子光晕
                                if target_pixel.0[3] < 90 {
                                    *target_pixel = image::Rgba([0, 229, 255, 90]);
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    Ok(image)
}

fn words(line: &str) -> Vec<(char, f64)> {
    let line = line.split(';').next().unwrap_or("");
    let mut out = Vec::new();
    let bytes = line.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'(' {
            while i < bytes.len() && bytes[i] != b')' {
                i += 1;
            }
            i += 1;
            continue;
        }
        if bytes[i].is_ascii_alphabetic() {
            let letter = bytes[i].to_ascii_uppercase() as char;
            let start = i;
            i += 1;
            while i < bytes.len()
                && (bytes[i].is_ascii_digit()
                    || matches!(bytes[i], b'+' | b'-' | b'.' | b'e' | b'E'))
            {
                i += 1;
            }
            if i > start + 1 {
                if let Ok(value) = line[start + 1..i].parse() {
                    out.push((letter, value));
                }
            }
        } else {
            i += 1;
        }
    }
    out
}

pub fn parse_moves(text: &str) -> Vec<Move> {
    let mut motion = 0;
    let mut feed = None;
    let mut power = None;
    let mut out = Vec::new();
    for line in text.lines() {
        let ws = words(line);
        for &(letter, value) in &ws {
            if letter == 'G'
                && matches!(value as i32, 0 | 1)
                && (value - value.round()).abs() < 1e-9
            {
                motion = value as i32;
            } else if letter == 'F' {
                feed = Some(value);
            } else if letter == 'S' {
                power = Some(value);
            }
        }
        if ws
            .iter()
            .any(|&(l, v)| l == 'G' && (v - v.round()).abs() < 1e-9 && matches!(v as i32, 0 | 1))
            && ws.iter().any(|&(l, _)| l == 'X' || l == 'Y')
        {
            out.push(Move {
                x: ws.iter().rev().find(|(l, _)| *l == 'X').map(|(_, v)| *v),
                y: ws.iter().rev().find(|(l, _)| *l == 'Y').map(|(_, v)| *v),
                feed_rate: feed,
                power,
                rapid: motion == 0,
            });
        }
    }
    out
}

pub fn write_move(m: &Move) -> String {
    let mut line = if m.rapid { "G0" } else { "G1" }.to_owned();
    if let Some(x) = m.x {
        write!(line, " X{x:.3}").unwrap();
    }
    if let Some(y) = m.y {
        write!(line, " Y{y:.3}").unwrap();
    }
    if let Some(feed) = m.feed_rate {
        write!(line, " F{feed:.0}").unwrap();
    }
    if let Some(power) = m.power {
        write!(line, " S{power:.0}").unwrap();
    }
    line
}

pub fn estimate_time_seconds(text: &str, rapid_mm_per_minute: f64) -> f64 {
    estimate_time(text, rapid_mm_per_minute).estimated_seconds
}

pub fn estimate_time(text: &str, rapid_rate: f64) -> TimeEstimate {
    let mut x = 0.0;
    let mut y = 0.0;
    let mut feed = 0.0;
    let mut power = 0.0;
    let mut motion = 0;
    let mut spindle = 5;
    let mut absolute = true;
    let mut ox = 0.0;
    let mut oy = 0.0;
    let mut laser_seconds = 0.0;
    let mut non_laser_seconds = 0.0;
    let mut laser_distance = 0.0;
    let mut non_laser_distance = 0.0;
    for line in text.lines() {
        let ws = words(line);
        if ws.is_empty() {
            continue;
        }
        for &(l, v) in &ws {
            match l {
                'G' if v.round() == 0.0
                    || v.round() == 1.0
                    || v.round() == 2.0
                    || v.round() == 3.0 =>
                {
                    motion = v as i32
                }
                'G' if v.round() == 90.0 => absolute = true,
                'G' if v.round() == 91.0 => absolute = false,
                'M' if (3.0..=5.0).contains(&v) => spindle = v as i32,
                'F' => feed = v,
                'S' => power = v,
                _ => {}
            }
        }
        if ws.iter().any(|&(l, v)| l == 'G' && v.round() == 92.0) {
            if let Some(v) = ws.iter().find(|(l, _)| *l == 'X').map(|(_, v)| *v) {
                ox = x - v;
            }
            if let Some(v) = ws.iter().find(|(l, _)| *l == 'Y').map(|(_, v)| *v) {
                oy = y - v;
            }
            continue;
        }
        let px = x;
        let py = y;
        for &(l, v) in &ws {
            if l == 'X' {
                x = if absolute { v + ox } else { x + v };
            }
            if l == 'Y' {
                y = if absolute { v + oy } else { y + v };
            }
        }
        if ws.iter().any(|&(l, v)| l == 'G' && v.round() == 4.0) {
            let pause = ws
                .iter()
                .rev()
                .find(|(l, _)| *l == 'P' || *l == 'S')
                .map_or(0.0, |(_, v)| *v);
            non_laser_seconds += pause;
            continue;
        }
        let mut distance = (x - px).hypot(y - py);
        if motion == 2 || motion == 3 {
            if let (Some(i), Some(j)) = (
                ws.iter().rev().find(|(l, _)| *l == 'I').map(|(_, v)| *v),
                ws.iter().rev().find(|(l, _)| *l == 'J').map(|(_, v)| *v),
            ) {
                let radius = (px - (px + i)).hypot(py - (py + j));
                let start = (py - (py + j)).atan2(px - (px + i));
                let end = (y - (py + j)).atan2(x - (px + i));
                let sweep = if motion == 2 {
                    (start - end).rem_euclid(TAU)
                } else {
                    (end - start).rem_euclid(TAU)
                };
                if radius > 0.0 && sweep > 0.0 {
                    distance = radius * sweep;
                }
            } else if let Some(r) = ws.iter().rev().find(|(l, _)| *l == 'R').map(|(_, v)| *v) {
                let radius = r.abs();
                let chord = (x - px).hypot(y - py);
                if radius > 0.0 && chord <= 2.0 * radius {
                    let mut sweep = 2.0 * (chord / (2.0 * radius)).asin();
                    if r < 0.0 {
                        sweep = TAU - sweep;
                    }
                    if sweep > 0.0 {
                        distance = radius * sweep;
                    }
                }
            }
        }
        if distance == 0.0 {
            continue;
        }
        let rate = if motion == 0 {
            rapid_rate
        } else {
            feed.min(rapid_rate)
        };
        if rate <= 0.0 {
            continue;
        }
        let seconds = distance / rate * 60.0;
        if power > 0.0 && (spindle == 3 || (spindle == 4 && motion != 0)) {
            laser_seconds += seconds;
            laser_distance += distance;
        } else {
            non_laser_seconds += seconds;
            non_laser_distance += distance;
        }
    }
    let total = laser_seconds + non_laser_seconds;
    TimeEstimate {
        estimated_seconds: (total * 10.0).round() / 10.0,
        estimated_minutes: (total / 60.0 * 100.0).round() / 100.0,
        laser_seconds: (laser_seconds * 10.0).round() / 10.0,
        non_laser_seconds: (non_laser_seconds * 10.0).round() / 10.0,
        laser_distance_mm: (laser_distance * 1000.0).round() / 1000.0,
        non_laser_distance_mm: (non_laser_distance * 1000.0).round() / 1000.0,
    }
}

/// 检测 G-code 中声明的功率标尺（默认为 1000.0）
pub fn detect_gcode_power_scale(text: &str) -> Option<f64> {
    for line in text.lines() {
        let trimmed = line.trim();
        if let Some(pos) = trimmed.find("$30=") {
            let rest = &trimmed[pos + 4..];
            let num_str: String = rest.chars().take_while(|c| c.is_ascii_digit() || *c == '.').collect();
            if let Ok(val) = num_str.parse::<f64>() {
                if val > 0.0 {
                    return Some(val);
                }
            }
        }
    }
    None
}

/// 按目标标尺（例如 255 或 1000）等比例重算 G-code 中的 S 功率参数
pub fn rescale_gcode_power(text: &str, from_scale: f64, to_scale: f64) -> String {
    if (from_scale - to_scale).abs() < 1e-6 || from_scale <= 0.0 || to_scale <= 0.0 {
        return text.to_string();
    }
    let ratio = to_scale / from_scale;
    let mut out = String::with_capacity(text.len());
    for line in text.lines() {
        let (content, comment) = match line.find(';') {
            Some(idx) => (&line[..idx], Some(&line[idx..])),
            None => (line, None),
        };

        let mut new_content = String::with_capacity(content.len());
        let mut chars = content.chars().peekable();
        while let Some(c) = chars.next() {
            if (c == 'S' || c == 's')
                && chars.peek().is_some_and(|next| next.is_ascii_digit() || *next == '+' || *next == '-')
            {
                let mut num_str = String::new();
                while let Some(&next) = chars.peek() {
                    if next.is_ascii_digit() || next == '.' || next == '+' || next == '-' {
                        num_str.push(chars.next().unwrap());
                    } else {
                        break;
                    }
                }
                if let Ok(s_val) = num_str.parse::<f64>() {
                    let new_s = (s_val * ratio).round().clamp(0.0, to_scale) as i64;
                    new_content.push('S');
                    new_content.push_str(&new_s.to_string());
                } else {
                    new_content.push('S');
                    new_content.push_str(&num_str);
                }
            } else {
                new_content.push(c);
            }
        }

        out.push_str(&new_content);
        if let Some(comm) = comment {
            let from_pattern = format!("$30={}", from_scale as i64);
            let to_pattern = format!("$30={}", to_scale as i64);
            if comm.contains(&from_pattern) {
                out.push_str(&comm.replace(&from_pattern, &to_pattern));
            } else {
                out.push_str(comm);
            }
        }
        out.push('\n');
    }
    out
}

