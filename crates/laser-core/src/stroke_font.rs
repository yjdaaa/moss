//! 内置单线字体（2026-11-16，材料测试与线距测试的行列标注用）。
//!
//! 对齐 LightBurn Material Test / Interval Test 在样板上刻出参数值，但不依赖系统字体：
//! 结果与平台无关、刀路逐字节可复现（SHA 门禁稳定），每个字只走几笔单线，
//! 比轮廓字体填充快得多。只收录标注需要的字符：数字、`. - % / ( )`、空格与大写字母。
//!
//! 字形画在宽 4、高 6 的格子里（y 向上，基线 y = 0），按 `height_mm / 6` 缩放。

use laser_contracts::geometry::{Paths, Point};

/// 字形格子高度（字形单位）。
const GLYPH_UNITS_HIGH: f64 = 6.0;
/// 字间距（字形单位）。
const GLYPH_GAP_UNITS: f64 = 1.5;

/// 八边形近似的圆形字身（O、0、Q 共用）。
