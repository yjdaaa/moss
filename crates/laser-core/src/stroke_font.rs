/// 单线文字：返回笔画（y 向上，左下角为原点，基线 y = 0）与总宽度（mm）。
/// 小写字母按大写处理；不支持的字符返回错误，不静默丢字。
pub fn stroke_text(text: &str, height_mm: f64) -> Result<(Paths, f64), &'static str> {
    if !height_mm.is_finite() || height_mm <= 0.0 {
        return Err("label height must be positive");
    }
    let scale = height_mm / GLYPH_UNITS_HIGH;
    let mut paths = Vec::new();
    let mut x = 0.0;
    let mut first = true;
    for ch in text.chars() {
        let (width, strokes) =
            glyph(ch.to_ascii_uppercase()).ok_or("unsupported label character")?;
        if !first {
            x += GLYPH_GAP_UNITS * scale;
        }
        first = false;
        for stroke in strokes {
            paths.push(
                stroke
                    .iter()
                    .map(|&(gx, gy)| (x + gx * scale, gy * scale))
                    .collect::<Vec<Point>>(),
            );
        }
        x += width * scale;
    }
    Ok((paths, x))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn digits_letters_and_symbols_render_inside_their_box() {
        let text = "0123456789 .-%/() ABCDEFGHIJKLMNOPQRSTUVWXYZ";
        let (paths, width) = stroke_text(text, 3.0).unwrap();
        assert!(!paths.is_empty());
        assert!(width > 0.0);
        for point in paths.iter().flatten() {
            assert!((0.0..=width + 1e-9).contains(&point.0), "{point:?}");
            assert!((0.0..=3.0 + 1e-9).contains(&point.1), "{point:?}");
        }
    }

    #[test]
    fn width_scales_with_height_and_lowercase_maps_to_uppercase() {
        let (_, small) = stroke_text("12", 3.0).unwrap();
        let (_, large) = stroke_text("12", 6.0).unwrap();
        assert!((large - 2.0 * small).abs() < 1e-9);
        assert_eq!(stroke_text("mm", 3.0), stroke_text("MM", 3.0));
    }

    #[test]
    fn unsupported_characters_and_bad_heights_are_rejected() {
        assert!(stroke_text("椴木", 3.0).is_err());
        assert!(stroke_text("1", 0.0).is_err());
        assert!(stroke_text("1", f64::NAN).is_err());
    }
}
