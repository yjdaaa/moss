//! 光栅（逐行扫描）与灰度可变功率写出。

use crate::raster::RasterPlan;

#[derive(Debug, Clone, PartialEq)]
pub struct RasterWriterOptions {
    pub pixel_size_mm: f64,
    pub overscan_mm: f64,
    pub work_area_width_mm: f64,
    pub work_area_height_mm: f64,
    pub power: i32,
    pub feed_rate: i32,
    pub laser_mode: &'static str,
    pub snake_scan: bool,
    pub material: Option<String>,
    pub safety_note: Option<String>,
    pub power_scale: Option<i32>,
    /// 点宽补偿（mm，LightBurn Dot Width Correction，2026-11-16）：每段出光两端各缩短一半，
    /// 抵消光斑直径让线段比像素更长；0 表示不补偿，必须小于行间距（`pixel_size_mm`）。
    pub dot_width_mm: f64,
}

fn valid_dot_width(options: &RasterWriterOptions) -> bool {
    options.dot_width_mm.is_finite()
        && options.dot_width_mm >= 0.0
        && options.dot_width_mm < options.pixel_size_mm
}

pub fn write_raster(
    plan: &RasterPlan,
    grid_width: usize,
    grid_height: usize,
    options: &RasterWriterOptions,
) -> Result<String, &'static str> {
    let scale = options.power_scale.unwrap_or(1000);
    if grid_width == 0
        || grid_height == 0
        || !options.pixel_size_mm.is_finite()
        || options.pixel_size_mm <= 0.0
        || !options.overscan_mm.is_finite()
        || options.overscan_mm < 0.0
        || !options.work_area_width_mm.is_finite()
        || options.work_area_width_mm <= 0.0
        || !options.work_area_height_mm.is_finite()
        || options.work_area_height_mm <= 0.0
        || options.power < 0
        || options.power > scale
        || options.feed_rate < 1
        || !valid_dot_width(options)
    {
        return Err("invalid raster writer options");
    }
    let trim = options.dot_width_mm / 2.0;

    let height_mm = grid_height as f64 * options.pixel_size_mm;
    let material_str = options.material.as_deref().unwrap_or("generic");
    let note_str = options.safety_note.as_deref().unwrap_or("auto");

    let mut lines = vec![
        "; Generated by ai-laser-gcode-nc".to_string(),
        format!("; GRBL laser mode expected: $30={scale}, $32=1"),
        format!("; Material: {}; note: {}", material_str, note_str),
        "; Raster mode: black/white dithered scan".to_string(),
        "G21".to_string(),
        "G90".to_string(),
        "G94".to_string(),
        "G17".to_string(),
        "G92 X0 Y0 Z0".to_string(),
        format!("{} S0", options.laser_mode),
        "G0 F3000".to_string(),
    ];

    let segments = if plan.selected_axis == "vertical" {
        &plan.vertical
    } else {
        &plan.horizontal
    };

    #[derive(Clone, Copy)]
    struct MachineSegment {
        start_x_mm: f64,
        end_x_mm: f64,
        y_mm: f64,
        end_y_mm: f64,
    }

    let is_vertical = plan.selected_axis == "vertical";
    let mut machine_segs: Vec<MachineSegment> = segments
        .iter()
        .map(|seg| {
            if is_vertical {
                let start_x_mm = seg.line as f64 * options.pixel_size_mm;
                let orig_y = seg.start as f64 * options.pixel_size_mm;
                let orig_end_y = seg.end as f64 * options.pixel_size_mm;
                MachineSegment {
                    start_x_mm,
                    end_x_mm: start_x_mm,
                    y_mm: (height_mm - orig_end_y).max(0.0),
                    end_y_mm: (height_mm - orig_y).max(0.0),
                }
            } else {
                let orig_y = seg.line as f64 * options.pixel_size_mm;
                let y_mm = (height_mm - options.pixel_size_mm - orig_y).max(0.0);
                MachineSegment {
                    start_x_mm: seg.start as f64 * options.pixel_size_mm,
                    end_x_mm: seg.end as f64 * options.pixel_size_mm,
                    y_mm,
                    end_y_mm: y_mm,
                }
            }
        })
        .collect();
    if is_vertical {
        machine_segs.sort_by(|a, b| {
            a.start_x_mm
                .total_cmp(&b.start_x_mm)
                .then_with(|| a.y_mm.total_cmp(&b.y_mm))
                .then_with(|| a.end_y_mm.total_cmp(&b.end_y_mm))
        });
    } else {
        machine_segs.sort_by(|a, b| {
            a.y_mm
                .total_cmp(&b.y_mm)
                .then_with(|| a.start_x_mm.total_cmp(&b.start_x_mm))
                .then_with(|| a.end_x_mm.total_cmp(&b.end_x_mm))
        });
    }

    let mut current_feed: Option<i32> = None;
    let mut next_feed_suffix = |feed_rate: i32| -> String {
        if current_feed != Some(feed_rate) {
            current_feed = Some(feed_rate);
            format!(" F{feed_rate}")
        } else {
            String::new()
        }
    };
    let sweep_axis = if is_vertical { 'Y' } else { 'X' };
    let max_sweep_mm = if is_vertical {
        options.work_area_height_mm
    } else {
        options.work_area_width_mm
    };
    let format_rapid = |fixed_coord: f64, sweep_coord: f64| -> String {
        if is_vertical {
            format!("G0 X{fixed_coord:.3} Y{sweep_coord:.3}")
        } else {
            format!("G0 X{sweep_coord:.3} Y{fixed_coord:.3}")
        }
    };

    if plan.output_strategy == "scanline" {
        let mut groups: Vec<Vec<MachineSegment>> = Vec::new();
        for seg in machine_segs {
            let key = if is_vertical {
                seg.start_x_mm
            } else {
                seg.y_mm
            };
            if let Some(last_group) = groups.last_mut() {
                let last_key = if is_vertical {
                    last_group[0].start_x_mm
                } else {
                    last_group[0].y_mm
                };
                if (key - last_key).abs() < 1e-6 {
                    last_group.push(seg);
                    continue;
                }
            }
            groups.push(vec![seg]);
        }

        for (line_index, line_segs) in groups.into_iter().enumerate() {
            if line_segs.is_empty() {
                continue;
            }
            let reverse = options.snake_scan && line_index % 2 == 1;
            let fixed_coord = if is_vertical {
                line_segs[0].start_x_mm
            } else {
                line_segs[0].y_mm
            };
            let mut shifted_runs: Vec<(f64, f64)> = line_segs
                .iter()
                .map(|seg| {
                    if is_vertical {
                        (
                            seg.y_mm + options.overscan_mm,
                            seg.end_y_mm + options.overscan_mm,
                        )
                    } else {
                        (
                            seg.start_x_mm + options.overscan_mm,
                            seg.end_x_mm + options.overscan_mm,
                        )
                    }
                })
                .collect();
            shifted_runs.sort_by(|a, b| a.0.total_cmp(&b.0));

            let min_start = shifted_runs
                .iter()
                .map(|(s, _)| *s)
                .fold(f64::INFINITY, f64::min);
            let max_end = shifted_runs
                .iter()
                .map(|(_, e)| *e)
                .fold(f64::NEG_INFINITY, f64::max);
            let scan_start = (min_start - options.overscan_mm).max(0.0);
            let scan_end = (max_end + options.overscan_mm).min(max_sweep_mm);
            if trim > 0.0 {
                for run in &mut shifted_runs {
                    *run = (run.0 + trim, run.1 - trim);
                }
            }

            if reverse {
                lines.push(format_rapid(fixed_coord, scan_end));
                for (start_pos, end_pos) in shifted_runs.into_iter().rev() {
                    let f_part = next_feed_suffix(options.feed_rate);
                    lines.push(format!("G1 {sweep_axis}{end_pos:.3} S0{f_part}"));
                    lines.push(format!("G1 {sweep_axis}{start_pos:.3} S{}", options.power));
                }
                lines.push(format!("G1 {sweep_axis}{scan_start:.3} S0"));
            } else {
                lines.push(format_rapid(fixed_coord, scan_start));
                for (start_pos, end_pos) in shifted_runs {
                    let f_part = next_feed_suffix(options.feed_rate);
                    lines.push(format!("G1 {sweep_axis}{start_pos:.3} S0{f_part}"));
                    lines.push(format!("G1 {sweep_axis}{end_pos:.3} S{}", options.power));
                }
                lines.push(format!("G1 {sweep_axis}{scan_end:.3} S0"));
            }
        }
    } else {
        for seg in segments {
            let (fixed_coord, start_pos, end_pos) = if is_vertical {
                let x_coord = seg.line as f64 * options.pixel_size_mm;
                let orig_y = seg.start as f64 * options.pixel_size_mm;
                let orig_end_y = seg.end as f64 * options.pixel_size_mm;
                let machine_y = (height_mm - orig_end_y).max(0.0);
                let machine_end_y = (height_mm - orig_y).max(0.0);
                (
                    x_coord,
                    machine_y + options.overscan_mm,
                    machine_end_y + options.overscan_mm,
                )
            } else {
                let orig_y = seg.line as f64 * options.pixel_size_mm;
                let y_coord = (height_mm - options.pixel_size_mm - orig_y).max(0.0);
                (
                    y_coord,
                    seg.start as f64 * options.pixel_size_mm + options.overscan_mm,
                    seg.end as f64 * options.pixel_size_mm + options.overscan_mm,
                )
            };
            let overscan_start = (start_pos - options.overscan_mm).max(0.0);
            let overscan_end = (end_pos + options.overscan_mm).min(max_sweep_mm);
            let (start_pos, end_pos) = (start_pos + trim, end_pos - trim);

            lines.push(format_rapid(fixed_coord, overscan_start));
            let f_part = next_feed_suffix(options.feed_rate);
            lines.push(format!("G1 {sweep_axis}{start_pos:.3} S0{f_part}"));
            lines.push(format!("G1 {sweep_axis}{end_pos:.3} S{}", options.power));
            lines.push(format!("G1 {sweep_axis}{overscan_end:.3} S0"));
        }
    }

    lines.push("M5".to_string());
    lines.push("M2".to_string());
    Ok(lines.join("\n") + "\n")
}

/// 灰度（变功率）栅格写出（LightBurn Grayscale，2026-11-16）：只做横向扫描线。
/// `levels[y][x]` 为灰度级（0 = 纯白不出光），`power_table[级]` 为该级的 S 值；同一行相邻、功率相同的像素
/// 合成一段 `G1 X… S…`，功率变化时直接换 S 不插空走。每段连续出光区两端按 `dot_width_mm` 各缩短一半。
/// 头尾、过扫描、蛇形换向与 [`write_raster`] 的 scanline 一致；所有 S 值必须在 `0..=power` 且不超过功率标尺。
pub fn write_grayscale_raster(
    levels: &[Vec<u8>],
    power_table: &[i32],
    options: &RasterWriterOptions,
) -> Result<String, &'static str> {
    let scale = options.power_scale.unwrap_or(1000);
    let grid_width = levels.first().map_or(0, Vec::len);
    if levels.is_empty()
        || grid_width == 0
        || levels.iter().any(|row| row.len() != grid_width)
        || !options.pixel_size_mm.is_finite()
        || options.pixel_size_mm <= 0.0
        || !options.overscan_mm.is_finite()
        || options.overscan_mm < 0.0
        || !options.work_area_width_mm.is_finite()
        || options.work_area_width_mm <= 0.0
        || !options.work_area_height_mm.is_finite()
        || options.work_area_height_mm <= 0.0
        || options.power < 0
        || options.power > scale
        || options.feed_rate < 1
        || !valid_dot_width(options)
        || power_table.first() != Some(&0)
        || power_table.iter().any(|p| *p < 0 || *p > options.power)
        || levels
            .iter()
            .flatten()
            .any(|level| usize::from(*level) >= power_table.len())
    {
        return Err("invalid grayscale raster writer options");
    }
    let pixel = options.pixel_size_mm;
    let height_mm = levels.len() as f64 * pixel;
    let trim = options.dot_width_mm / 2.0;
    let mut lines = vec![
        "; Generated by ai-laser-gcode-nc".to_string(),
        format!("; GRBL laser mode expected: $30={scale}, $32=1"),
        format!(
            "; Material: {}; note: {}",
            options.material.as_deref().unwrap_or("generic"),
            options.safety_note.as_deref().unwrap_or("auto")
        ),
        format!(
            "; Raster mode: grayscale variable power ({} levels)",
            power_table.len()
        ),
        "G21".to_string(),
        "G90".to_string(),
        "G94".to_string(),
        "G17".to_string(),
        "G92 X0 Y0 Z0".to_string(),
        format!("{} S0", options.laser_mode),
        "G0 F3000".to_string(),
    ];
    let mut current_feed: Option<i32> = None;
    let mut feed_suffix = || {
        if current_feed != Some(options.feed_rate) {
            current_feed = Some(options.feed_rate);
            format!(" F{}", options.feed_rate)
        } else {
            String::new()
        }
    };
    let mut emitted_lines = 0_usize;
    // 机器 Y 自下而上：图像最后一行最先加工，与 write_raster 的排序一致
    for (line, row) in levels.iter().enumerate().rev() {
        // (起点 mm, 终点 mm, S) — 已右移一个过扫描距离
        let mut runs: Vec<(f64, f64, i32)> = Vec::new();
        let mut x = 0;
        while x < grid_width {
            let power = power_table[usize::from(row[x])];
            let begin = x;
            while x < grid_width && power_table[usize::from(row[x])] == power {
                x += 1;
            }
            if power > 0 {
                runs.push((
                    begin as f64 * pixel + options.overscan_mm,
                    x as f64 * pixel + options.overscan_mm,
                    power,
                ));
            }
        }
        if runs.is_empty() {
            continue;
        }
        let scan_start = (runs[0].0 - options.overscan_mm).max(0.0);
        let scan_end =
            (runs[runs.len() - 1].1 + options.overscan_mm).min(options.work_area_width_mm);
        if trim > 0.0 {
            // 只缩短连续出光区的外侧两端；区内功率切换处不留缝
            for index in 0..runs.len() {
                let joined_before = index > 0 && (runs[index - 1].1 - runs[index].0).abs() < 1e-9;
                let joined_after =
                    index + 1 < runs.len() && (runs[index].1 - runs[index + 1].0).abs() < 1e-9;
                if !joined_before {
                    runs[index].0 += trim;
                }
                if !joined_after {
                    runs[index].1 -= trim;
                }
            }
        }
        let y = (height_mm - pixel - line as f64 * pixel).max(0.0);
        let reverse = options.snake_scan && emitted_lines % 2 == 1;
        emitted_lines += 1;
        if reverse {
            lines.push(format!("G0 X{scan_end:.3} Y{y:.3}"));
            let mut cursor = scan_end;
            for (start, end, power) in runs.into_iter().rev() {
                if (cursor - end).abs() > 1e-9 {
                    let f = feed_suffix();
                    lines.push(format!("G1 X{end:.3} S0{f}"));
                }
                let f = feed_suffix();
                lines.push(format!("G1 X{start:.3} S{power}{f}"));
                cursor = start;
            }
            lines.push(format!("G1 X{scan_start:.3} S0"));
        } else {
            lines.push(format!("G0 X{scan_start:.3} Y{y:.3}"));
            let mut cursor = scan_start;
            for (start, end, power) in runs {
                if (cursor - start).abs() > 1e-9 {
                    let f = feed_suffix();
                    lines.push(format!("G1 X{start:.3} S0{f}"));
                }
                let f = feed_suffix();
                lines.push(format!("G1 X{end:.3} S{power}{f}"));
                cursor = end;
            }
            lines.push(format!("G1 X{scan_end:.3} S0"));
        }
    }
    lines.push("M5".to_string());
    lines.push("M2".to_string());
    Ok(lines.join("\n") + "\n")
}
