//! 首次标定向导的测试图案（r40，2026-11-16 用户决定）：只生成 G-code，不出光；发送走材料实验室
//! 现有的确认与门禁。
//!
//! - **扫描方块** [`scan_squares_gcode`]：一排实心方块，每块按自己的速度、过扫描与双向扫描偏移来回横扫
//!   （偶数行往右、奇数行往左）。双向扫描偏移测试用偏移 0、不同速度；过扫描检查用同一速度、
//!   左块不过扫描、右块按当前设置过扫描。偏移的含义与 [`crate::vector_plan`] 相同：
//!   每行逆着自己的行进方向挪偏移的一半，所以“来回两行出光错位多少 mm”就填多少。
//! - **切缝方块** [`kerf_square_gcode`]：按切割参数沿方块外框切一圈（不做切缝补偿）。量切下来的方块边长
//!   `m`，切缝宽度 `w = 设计边长 − m`（每边各被烧掉 `w/2`），切缝补偿 `kerf_mm = w / 2`，见 [`kerf_offset_mm`]。

/// 一个扫描方块的加工参数。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ScanSquareSpec {
    pub power: i32,
    pub speed: i32,
    pub overscan_mm: f64,
    pub scan_offset_mm: f64,
}

/// 排好位置的扫描方块（左下角坐标，mm）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PlacedSquare {
    pub spec: ScanSquareSpec,
    pub x_mm: f64,
    pub y_mm: f64,
}

/// 扫描方块图案：方块位置、整体范围（含过扫描）与 G-code。
#[derive(Debug, Clone, PartialEq)]
pub struct ScanPattern {
    pub squares: Vec<PlacedSquare>,
    pub size_mm: f64,
    pub width_mm: f64,
    pub height_mm: f64,
    pub gcode: String,
}

/// 方块之间的空隙（mm，不含过扫描）。
pub const SQUARE_GAP_MM: f64 = 4.0;
/// 方块边长范围（mm）。
pub const SQUARE_SIZE_RANGE_MM: (f64, f64) = (5.0, 50.0);
/// 一个图案最多几个方块。
pub const MAX_SQUARES: usize = 8;

fn header(material: &str, note: &str) -> Vec<String> {
    vec![
        "; Generated by laser-core (calibration wizard pattern)".to_owned(),
        format!("; {note}"),
        format!("; Material: {material}"),
        "G21".into(),
        "G90".into(),
        "G94".into(),
        "G17".into(),
        "G92 X0 Y0 Z0".into(),
        "M4 S0".into(),
        "G0 F3000".into(),
    ]
}

/// 一排双向横扫的实心方块（见模块说明）。坐标都不小于 0：第一个方块左边留出过扫描与偏移的距离。
pub fn scan_squares_gcode(
    material: &str,
    note: &str,
    specs: &[ScanSquareSpec],
    size_mm: f64,
    interval_mm: f64,
) -> Result<ScanPattern, &'static str> {
    if material.is_empty() || specs.is_empty() || specs.len() > MAX_SQUARES {
        return Err("scan pattern needs a material and 1..8 squares");
    }
    if !size_mm.is_finite() || !(SQUARE_SIZE_RANGE_MM.0..=SQUARE_SIZE_RANGE_MM.1).contains(&size_mm)
    {
        return Err("square size must be 5..50 mm");
    }
    if !interval_mm.is_finite() || !(0.01..=2.0).contains(&interval_mm) {
        return Err("line interval must be 0.01..2 mm");
    }
    for spec in specs {
        if !(0..=1000).contains(&spec.power)
            || spec.speed < 1
            || !spec.overscan_mm.is_finite()
            || !(0.0..=crate::vector_plan::MAX_OVERSCAN_MM).contains(&spec.overscan_mm)
            || !spec.scan_offset_mm.is_finite()
            || spec.scan_offset_mm.abs() > crate::vector_plan::MAX_SCAN_OFFSET_MM
        {
            return Err("square power/speed/overscan/offset out of range");
        }
    }
    let rows = (size_mm / interval_mm + 1e-9).floor() as usize + 1;
    let mut lines = header(material, note);
    let mut squares = Vec::with_capacity(specs.len());
    let mut cursor = 0.0_f64;
    for (index, spec) in specs.iter().enumerate() {
        let reach = spec.overscan_mm + spec.scan_offset_mm.abs() / 2.0;
        let x0 = cursor + reach;
        let x1 = x0 + size_mm;
        cursor = x1 + reach + SQUARE_GAP_MM;
        squares.push(PlacedSquare {
            spec: *spec,
            x_mm: x0,
            y_mm: 0.0,
        });
        lines.push(format!(
            "; Square {}: S{} F{} overscan={:.2} offset={:.3}",
            index + 1,
            spec.power,
            spec.speed,
            spec.overscan_mm,
            spec.scan_offset_mm
        ));
        let half = spec.scan_offset_mm / 2.0;
        for row in 0..rows {
            let y = row as f64 * interval_mm;
            // 偶数行往右、奇数行往左；每行逆着行进方向挪偏移的一半
            let dir = if row % 2 == 0 { 1.0 } else { -1.0 };
            let (start, end) = if dir > 0.0 { (x0, x1) } else { (x1, x0) };
            let (start, end) = (start - dir * half, end - dir * half);
            let os = spec.overscan_mm;
            lines.push(format!("G0 X{:.3} Y{y:.3}", start - dir * os));
            if os > 0.0 {
                lines.push(format!("G1 X{start:.3} Y{y:.3} S0 F{}", spec.speed));
            }
            lines.push(format!(
                "G1 X{end:.3} Y{y:.3} S{} F{}",
                spec.power, spec.speed
            ));
            if os > 0.0 {
                lines.push(format!("G1 X{:.3} Y{y:.3} S0", end + dir * os));
            }
        }
        lines.push("S0".into());
    }
    lines.extend(["M5".into(), "M2".into()]);
    let width_mm = (cursor - SQUARE_GAP_MM).max(0.0);
    let height_mm = (rows - 1) as f64 * interval_mm;
    Ok(ScanPattern {
        squares,
        size_mm,
        width_mm,
        height_mm,
        gcode: lines.join("\n") + "\n",
    })
}

/// 沿 `size_mm` 见方的外框切 `passes` 圈（左下角为激光头起点，不做切缝补偿）。
pub fn kerf_square_gcode(
    material: &str,
    size_mm: f64,
    power: i32,
    speed: i32,
    passes: i32,
) -> Result<String, &'static str> {
    if material.is_empty()
        || !size_mm.is_finite()
        || !(SQUARE_SIZE_RANGE_MM.0..=SQUARE_SIZE_RANGE_MM.1).contains(&size_mm)
    {
        return Err("kerf square needs a material and a 5..50 mm size");
    }
    if !(0..=1000).contains(&power) || speed < 1 || !(1..=20).contains(&passes) {
        return Err("kerf square power/speed/passes out of range");
    }
    let mut lines = header(
        material,
        &format!("Kerf test: cut a {size_mm:.1} mm square, measure the piece"),
    );
    lines.push("G0 X0.000 Y0.000".into());
    for pass in 0..passes {
        lines.push(format!("; Pass {}", pass + 1));
        for (x, y) in [
            (size_mm, 0.0),
            (size_mm, size_mm),
            (0.0, size_mm),
            (0.0, 0.0),
        ] {
            lines.push(format!("G1 X{x:.3} Y{y:.3} S{power} F{speed}"));
        }
    }
    lines.extend(["S0".into(), "M5".into(), "M2".into()]);
    Ok(lines.join("\n") + "\n")
}

/// 切缝补偿：切下来的方块量得 `measured_mm`，设计边长 `design_mm`。每条边被烧掉切缝宽度的一半，
/// 所以切缝宽度 `w = design − measured`，补偿（外轮廓往外挪）`kerf_mm = w / 2`。
/// 结果超出 ±[`crate::cut::MAX_KERF_MM`] 或输入无效时返回 `None`。
pub fn kerf_offset_mm(design_mm: f64, measured_mm: f64) -> Option<f64> {
    if !design_mm.is_finite() || !measured_mm.is_finite() || design_mm <= 0.0 || measured_mm <= 0.0
    {
        return None;
    }
    let kerf = (design_mm - measured_mm) / 2.0;
    let rounded = (kerf * 1000.0).round() / 1000.0;
    (rounded.abs() <= crate::cut::MAX_KERF_MM).then_some(rounded)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn burn_rows(gcode: &str) -> Vec<(f64, f64)> {
        // 每条出光行的 (起点 x, 终点 x)
        let mut rows = Vec::new();
        let mut last_x = 0.0;
        for line in gcode.lines() {
            let x = line
                .split_whitespace()
                .find_map(|w| w.strip_prefix('X'))
                .and_then(|v| v.parse::<f64>().ok());
            let burning = line.starts_with("G1") && !line.contains(" S0");
            if let Some(x) = x {
                if burning {
                    rows.push((last_x, x));
                }
                last_x = x;
            }
        }
        rows
    }

    #[test]
    fn scan_squares_alternate_direction_and_apply_offset_against_travel() {
        let spec = ScanSquareSpec {
            power: 300,
            speed: 1500,
            overscan_mm: 0.0,
            scan_offset_mm: 0.2,
        };
        let pattern = scan_squares_gcode("椴木", "test", &[spec], 5.0, 1.0).unwrap();
        let rows = burn_rows(&pattern.gcode);
        assert_eq!(rows.len(), 6);
        // 第一块左边留出偏移的一半：x0 = 0.1；往右的行整体左挪 0.1，往左的行整体右挪 0.1
        assert!((rows[0].0 - 0.0).abs() < 1e-9 && (rows[0].1 - 5.0).abs() < 1e-9);
        assert!((rows[1].0 - 5.2).abs() < 1e-9 && (rows[1].1 - 0.2).abs() < 1e-9);
        assert!(pattern.gcode.contains("G92 X0 Y0 Z0"));
        assert!(pattern.gcode.trim_end().ends_with("M2"));
    }

    #[test]
    fn scan_squares_overscan_coasts_with_laser_off_and_never_goes_negative() {
        let specs = [
            ScanSquareSpec {
                power: 300,
                speed: 1500,
                overscan_mm: 0.0,
                scan_offset_mm: 0.0,
            },
            ScanSquareSpec {
                power: 300,
                speed: 1500,
                overscan_mm: 2.0,
                scan_offset_mm: 0.0,
            },
        ];
        let pattern = scan_squares_gcode("椴木", "test", &specs, 10.0, 0.5).unwrap();
        assert_eq!(pattern.squares[0].x_mm, 0.0);
        assert!((pattern.squares[1].x_mm - (10.0 + SQUARE_GAP_MM + 2.0)).abs() < 1e-9);
        assert!((pattern.width_mm - (10.0 + SQUARE_GAP_MM + 14.0)).abs() < 1e-9);
        for line in pattern.gcode.lines() {
            if let Some(x) = line
                .split_whitespace()
                .find_map(|w| w.strip_prefix('X'))
                .and_then(|v| v.parse::<f64>().ok())
            {
                assert!(x >= -1e-9, "{line}");
            }
        }
        // 过扫描段一律 S0
        assert!(pattern.gcode.contains("S0 F1500"));
        assert!(scan_squares_gcode("椴木", "t", &specs, 2.0, 0.5).is_err());
        assert!(scan_squares_gcode("椴木", "t", &[], 10.0, 0.5).is_err());
    }

    #[test]
    fn kerf_square_cuts_closed_outline_each_pass() {
        let gcode = kerf_square_gcode("椴木", 20.0, 900, 300, 2).unwrap();
        assert_eq!(gcode.matches("G1 X0.000 Y0.000 S900 F300").count(), 2);
        assert!(gcode.contains("G1 X20.000 Y20.000 S900 F300"));
        assert!(kerf_square_gcode("椴木", 20.0, 900, 300, 0).is_err());
    }

    #[test]
    fn kerf_offset_is_half_the_burned_width() {
        // 切下来 19.8 mm：切缝宽 0.2 mm，每边烧掉 0.1 mm，补偿往外 0.1 mm
        assert_eq!(kerf_offset_mm(20.0, 19.8), Some(0.1));
        assert_eq!(kerf_offset_mm(20.0, 20.0), Some(0.0));
        assert_eq!(kerf_offset_mm(20.0, 20.1), Some(-0.05));
        assert_eq!(kerf_offset_mm(20.0, 10.0), None);
        assert_eq!(kerf_offset_mm(20.0, f64::NAN), None);
    }
}
